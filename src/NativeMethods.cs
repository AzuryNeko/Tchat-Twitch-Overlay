        /// <summary>Thème Windows des applications (Paramètres > Personnalisation > Couleurs).</summary>
        public static bool SystemUsesDarkTheme()
        {
            try
            {
                using (var key = Microsoft.Win32.Registry.CurrentUser.OpenSubKey(@"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize"))
                    return key?.GetValue("AppsUseLightTheme") is int v && v == 0;
            }
            catch { return false; }
        }

        /// <summary>Convertit "Ctrl+Shift+F10" en modificateurs + touche virtuelle.</summary>
        public static bool TryParseHotkey(string s, out uint mods, out uint vk)
        {
            mods = 0; vk = 0;
            if (string.IsNullOrWhiteSpace(s)) return false;
            foreach (var raw in s.Split('+', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                switch (raw.ToLowerInvariant())
                {
                    case "ctrl": case "control": mods |= MOD_CONTROL; break;
                    case "shift": case "maj": mods |= MOD_SHIFT; break;
                    case "alt": mods |= MOD_ALT; break;
                    case "win": mods |= MOD_WIN; break;
                    default:
                        string k = raw;
                        if (k.Length == 1 && char.IsDigit(k[0])) k = "D" + k;
                        if (!Enum.TryParse<System.Windows.Input.Key>(k, true, out var key)) return false;
                        vk = (uint)System.Windows.Input.KeyInterop.VirtualKeyFromKey(key);
                        break;
                }
            }
            return vk != 0;
        }
    }
